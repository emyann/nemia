/** Where `exported` differs from `pinned`: each name dropped or added, worded with what to do. */
const drift = (entry: string, exported: string[], pinned: string[]): string[] => [
  ...pinned
    .filter((n) => !exported.includes(n))
    .map((n) => `${entry} no longer exports ${n}: re-export it by name from the entry, as before the move`),
  ...exported
    .filter((n) => !pinned.includes(n))
    .map((n) => `${entry} exports ${n}, which it did not: a new name on an entry is added here on purpose`),
];

test('REFUSED: an entry that drops a name, or gains one', () => {
  assert.deepEqual(drift('agent-orchestrator/run', ['assess', 'feedWords'], ['assess', 'composeBrief']), [
    'agent-orchestrator/run no longer exports composeBrief: re-export it by name from the entry, as before the move',
    'agent-orchestrator/run exports feedWords, which it did not: a new name on an entry is added here on purpose',
  ]);
});

test('each entry exports exactly its pinned names', async () => {
  for (const [entry, pinned] of Object.entries(PINNED)) {
    assert.deepEqual(drift(entry, Object.keys(await import(entry)), pinned), [], entry);
  }
});

test('no entry exports the shipped client secrets, nor anything that answers one', async () => {
  for (const entry of Object.keys(PINNED)) {
    const names = Object.keys(await import(entry));
    assert.deepEqual(
      names.filter((n) => /secret/i.test(n)),
      [],
      `${entry}: the shipped secret is handed to the engine inside the package, never to a caller`,
    );
  }
});

test("HARNESS_CHOICES, which the api offers on a step's form, is the runtime's own table from its vocabulary door, not a copy", async () => {
  const { HARNESS_CHOICES } = await import('agent-orchestrator');
  const vocabulary = await import('agent-runtime/vocabulary');
  assert.equal(HARNESS_CHOICES, vocabulary.HARNESS_CHOICES);
});
