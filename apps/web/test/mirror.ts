/**
 * The board's run mirror, generated from the document the api serves (`GET /openapi/v3/nemia/v1`) by Effect's own modules: its
 * `components.schemas` read as OpenAPI 3.1 (`JsonSchema.fromSchemaOpenApi3_1`), every component a root imported as a Schema
 * (`SchemaRepresentation.fromJsonSchemaMultiDocument`), lowered to one representation (`toRepresentations`) and printed as code
 * (`toCodeDocument`). This file only lays Effect's code out in a file, each component an exported Schema and its type.
 *
 * The document is read from `apps/api/src/openapi/print.ts` in a process of its own, over a scratch store, so the board imports nothing
 * of the api. `node test/mirror.ts` (`npm run mirror`, from apps/web) writes `src/lib/api/run.gen.ts`; `mirror.test.ts` refuses a
 * checked-in file that differs from what the document generates.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { JsonSchema, SchemaRepresentation } from 'effect';

const REPO = path.join(import.meta.dirname, '..', '..', '..');
const PRINT = path.join(REPO, 'apps', 'api', 'src', 'openapi', 'print.ts');
/** The checked-in mirror. */
export const MIRROR = path.join(import.meta.dirname, '..', 'src', 'lib', 'api', 'run.gen.ts');

/** The part of the served document the mirror is made of: its component schemas, by name. */
export type OpenApiDocument = { readonly components: { readonly schemas: Readonly<Record<string, JsonSchema.JsonSchema>> } };

/**
 * The document the api serves now, printed by the api's own `print.ts` with `WF_ROOT`, `AE_ROOT` and `HOME` in `root`, so loading the
 * orchestrator reads no person's store. Without a `root`, one is made under the temp directory and taken away after.
 */
export const documentNow = (root?: string): OpenApiDocument => {
  const dir = root ?? fs.mkdtempSync(path.join(os.tmpdir(), 'nemia-mirror-'));
  try {
    const env = { ...process.env, WF_ROOT: path.join(dir, 'wf'), AE_ROOT: path.join(dir, 'ae'), HOME: dir };
    return JSON.parse(execFileSync(process.execPath, [PRINT], { cwd: REPO, env, encoding: 'utf8' })) as OpenApiDocument;
  } finally {
    if (root === undefined) fs.rmSync(dir, { recursive: true, force: true });
  }
};

const HEADER = `/**
 * Generated by \`npm run mirror\` in apps/web from the document the api serves (\`GET /openapi/v3/nemia/v1\`), by Effect's
 * \`SchemaRepresentation.toCodeDocument\`. Never edited: change the run object's Schema, then run \`npm run mirror\` again
 * (\`test/mirror.test.ts\` refuses a file that differs from what the document generates).
 */
`;

/** The source text of `src/lib/api/run.gen.ts`: every component of the document's schemas, exported as a Schema and its type. */
export const mirrorOf = (document: OpenApiDocument): string => {
  const schemas = document.components.schemas;
  const names = Object.keys(schemas);
  if (names.length === 0) throw new Error('the document has no components.schemas: run `node apps/api/src/openapi/print.ts` and read it');
  const read = JsonSchema.fromSchemaOpenApi3_1({ $defs: schemas });
  const [head, ...tail] = names.map((name): JsonSchema.JsonSchema => ({ $ref: `#/$defs/${name}` }));
  const roots = SchemaRepresentation.fromJsonSchemaMultiDocument({
    dialect: read.dialect,
    schemas: [head, ...tail],
    definitions: read.definitions,
  });
  const [first, ...rest] = roots.map((schema) => schema.ast);
  const code = SchemaRepresentation.toCodeDocument(SchemaRepresentation.toRepresentations([first, ...rest]));

  const named = new Set([...code.references.nonRecursives.map(({ $ref }) => $ref), ...Object.keys(code.references.recursives)]);
  const unnamed = code.codes.filter((root) => !named.has(root.runtime));
  if (unnamed.length > 0) {
    throw new Error(
      `a root printed with no name of its own: give it an identifier in the run object's Schema (${unnamed.map((root) => root.runtime).join(', ')})`,
    );
  }

  const lines: string[] = [HEADER, "import { Schema } from 'effect';"];
  for (const artifact of code.artifacts) if (artifact._tag === 'Import') lines.push(artifact.importDeclaration);
  lines.push('');
  for (const artifact of code.artifacts) {
    if (artifact._tag === 'Symbol') lines.push(`const ${artifact.identifier} = ${artifact.code.runtime};`);
    if (artifact._tag === 'Enum') lines.push(artifact.code.runtime);
  }
  for (const { $ref, code: one } of code.references.nonRecursives) {
    lines.push(`export const ${$ref} = ${one.runtime};`, `export type ${$ref} = ${one.Type};`, '');
  }
  for (const [$ref, one] of Object.entries(code.references.recursives)) {
    lines.push(`export type ${$ref} = ${one.Type};`, `export const ${$ref}: Schema.Codec<${$ref}> = ${one.runtime};`, '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
};

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  fs.writeFileSync(MIRROR, mirrorOf(documentNow()));
  process.stdout.write(`wrote ${path.relative(process.cwd(), MIRROR)}\n`);
}
