/**
 * Where the repository's Actions workflow is, how it parses, and which of its steps is the gate's; and, at the end, the clauses every
 * workflow of the repository is held to (an action of GitHub's own, a bound on every job and network step, no trigger that hands a
 * fork a writable token), read by `release-workflow.test.ts` too.
 *
 * Read by the guard that holds the file to the repository (`ci-workflow.test.ts`) and by the tests that run a step's own script
 * (`ci-gate.boundary.test.ts`, `ci-build.boundary.test.ts`, `ci-scan.boundary.test.ts`): one writer for the path and for what each of
 * those steps is, so the two cannot drift apart. What is about the repository and not about this workflow is not here: the owned paths
 * and the private packages are written where their one reader is (`repo-guards.test.ts`).
 */
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const ROOT = path.join(import.meta.dirname, '..', '..', '..');

/** The workflow, as every sentence that refuses it names it to the person who must fix it. */
export const FILE = '.github/workflows/ci.yml';

/** The job that reports the one context branch protection requires. */
export const GATE = 'ci';

/** The job whose matrix holds the legs: one workspace on one node version. */
export const LEGS = 'test';

/** The job whose matrix holds the e2e's shards: one shard of the pages each. */
export const E2E = 'e2e';

/** The job that sums every shard's page time against the bound a whole e2e run is held to. */
export const BOUND = 'e2e-bound';

/** The job that builds the board and refuses a generated file the build or the theme generator would rewrite. */
export const BUILD = 'build';

/**
 * The paths the build job's staleness step guards, each generated by a command and never edited: a stale one is a diff a person has not
 * committed, and the step names the command that writes it. A path here that the repository does not have is refused by the guard.
 */
export const GENERATED = ['apps/web/src/routeTree.gen.ts', 'apps/web/theme/'];

/** What the build job's staleness step is called, so the guard and the boundary test find the same step. */
export const STALE_STEP = 'Refuse a stale generated file';

/**
 * The workspace that has a job of its own rather than a leg, by its turbo name and its folder, and that job: the guards' suite runs
 * only when `due.ts` says the event touched what they read, a decision a matrix leg cannot carry.
 */
export const OWN_JOB = { name: 'guards', folder: 'tools/guards', job: 'guards' } as const;

/** The id of the guards job's step that decides whether the suite is due, and the command it runs. */
export const DUE_STEP = 'due';
export const DUE_COMMAND = 'node tools/guards/due.ts';

/** The condition the guards' suite step runs under: the due step's answer, so a skipped step leaves the job `success`. */
export const DUE_IF = "steps.due.outputs.due == 'true'";

/** The command the shards run, which the guard reads the shard's flags off. */
export const E2E_COMMAND = 'npm run e2e';

export type Step = {
  id?: string;
  name?: string;
  if?: string;
  uses?: string;
  with?: Record<string, unknown>;
  run?: string;
  env?: Record<string, string>;
  'timeout-minutes'?: unknown;
};

export type Job = {
  name?: string;
  if?: string;
  needs?: string[];
  permissions?: Record<string, string>;
  concurrency?: { group?: string; 'cancel-in-progress'?: unknown };
  strategy?: { 'fail-fast'?: boolean; matrix?: Record<string, unknown[]> };
  steps?: Step[];
  'timeout-minutes'?: unknown;
};

export type Workflow = {
  name?: string;
  on?: Record<
    string,
    {
      branches?: string[];
      types?: string[];
      paths?: string[];
      'paths-ignore'?: string[];
      inputs?: Record<string, { required?: boolean; type?: string; description?: string }>;
    } | null
  >;
  permissions?: Record<string, string>;
  concurrency?: { group?: string; 'cancel-in-progress'?: unknown };
  jobs: Record<string, Job>;
};

/** The workflow's own text, which two clauses read rather than its parse: a word in a comment is in the file all the same. */
export const workflowText = (): string => fs.readFileSync(path.join(ROOT, FILE), 'utf8');

export const readWorkflow = (text = workflowText()): Workflow => yaml.load(text) as Workflow;

/** The steps of `job` that run a command. */
export const runSteps = (workflow: Workflow, job: string): Step[] =>
  (workflow.jobs[job]?.steps ?? []).filter((step) => step.run !== undefined);

/** The e2e job's step that runs the e2e itself, which must hand it the leg's shard and the matrix's count. */
export const shardRunStep = (workflow: Workflow): Step | undefined =>
  runSteps(workflow, E2E).find((step) => step.run?.includes(E2E_COMMAND) === true);

/**
 * The build job's staleness step, by its name: what it decides is run rather than matched (`ci-build.boundary.test.ts`), since a
 * `git diff --exit-code` and a `git diff --name-only` that forgets to fail read alike to a pattern.
 */
export const staleStep = (workflow: Workflow): Step | undefined => runSteps(workflow, BUILD).find((step) => step.name === STALE_STEP);

/** The gate's steps that run a command: the one that turns the needed jobs' results into the `ci` context. */
export const gateSteps = (workflow: Workflow): Step[] => runSteps(workflow, GATE);

/** The job that scans the push's or the pull request's new commits for a secret. */
export const SCAN = 'gitleaks';

/** What the scan is configured by, and the one file that says what it allows, as the sentences that refuse a wider scan name it. */
export const SCAN_CONFIG = '.gitleaks.toml';

/**
 * What the scan job's step that proves its own allowlist is called, so the guard and the boundary test find the same step. What it
 * decides is run rather than matched (`ci-scan.boundary.test.ts`): the config's meaning is not in its text, and neither is the step's.
 */
export const ALLOWLIST_STEP = 'Prove the allowlist allows the stubs and nothing wider';

/** The scan job's step that scans the push's own commits, by the flags it carries: the one step of the job that reads git. */
export const scanStep = (workflow: Workflow): Step | undefined =>
  runSteps(workflow, SCAN).find((step) => step.run?.includes('--log-opts') === true);

/** The scan job's step that proves its allowlist, by its name. */
export const allowlistStep = (workflow: Workflow): Step | undefined =>
  runSteps(workflow, SCAN).find((step) => step.name === ALLOWLIST_STEP);

/**
 * GitHub's own action, taken by major tag: the pointer floats to its latest release, and a third party's never matches. This clause and
 * those below it hold every workflow of the repository, each taking the file's name for the sentence that names it.
 */
export const OWN_ACTION = /^actions\/[a-z][a-z\d-]*@v\d+$/;

/** A step that takes an action this workflow may not take. */
export function actionDrift(workflow: Workflow, file: string = FILE): string[] {
  return Object.entries(workflow.jobs).flatMap(([name, job]) =>
    (job.steps ?? [])
      .filter((step) => step.uses !== undefined && !OWN_ACTION.test(step.uses))
      .map(
        (step) =>
          `the ${name} job in ${file} takes ${String(step.uses)}: this workflow takes GitHub's own actions by major tag alone, so write it actions/<name>@v<major>, and take a third party's code as a pinned download in a run step instead`,
      ),
  );
}

/** The trigger that would run a fork's code with a token that can write, read from the file's own text. */
export function targetDrift(text: string, file: string = FILE): string[] {
  const trigger = ['pull', 'request', 'target'].join('_');
  return text.includes(trigger)
    ? [
        `${file} names ${trigger}: a fork's code must not run with a token that can write, so trigger on pull_request instead and read nothing of the fork's with write access`,
      ]
    : [];
}

/**
 * A run step that reaches the network: the lockfile's install, the browser's, a release fetched by hand, a call of GitHub's CLI, a
 * push or a fetch of git, and the release tool, whose verbs call both. Every action here reaches the network.
 */
export const NETWORK = /\bnpm ci\b|playwright install|\bcurl\b|(?:^|[\s;&|(])gh\s|\bgit (?:push|fetch)\b|tools\/release\/release\.ts/;

/** Whether a step reaches the network, and so must end at a bound of its own rather than at its job's. */
export const reachesNetwork = (step: Step): boolean => step.uses !== undefined || NETWORK.test(step.run ?? '');

/** A bound as GitHub takes it: a whole number of minutes above zero. */
export const bounded = (minutes: unknown): minutes is number => typeof minutes === 'number' && Number.isInteger(minutes) && minutes > 0;

/**
 * A job with no `timeout-minutes`, a step that reaches the network with none, and a step whose bound is not under its job's. Without
 * one GitHub waits 360 minutes on a stalled download, and the run's own wait on `ci` gives up long before; a step's bound at or past its
 * job's lets the job's fire first, and the red then names no step.
 */
export function stallDrift(workflow: Workflow, file: string = FILE): string[] {
  return Object.entries(workflow.jobs).flatMap(([name, job]) => {
    const minutes = job['timeout-minutes'];
    if (!bounded(minutes))
      return [
        `the ${name} job in ${file} has no timeout-minutes: give it a bound well above its slowest green run, or a stall holds it for GitHub's default of 360 minutes`,
      ];
    return (job.steps ?? []).flatMap((step) => {
      const label = step.name ?? step.uses ?? step.run ?? '?';
      const own = step['timeout-minutes'];
      if (!reachesNetwork(step)) return [];
      if (!bounded(own))
        return [
          `the step "${label}" of the ${name} job in ${file} reaches the network and has no timeout-minutes: give it a bound well above its slowest green run, so a stalled download fails naming the step`,
        ];
      if (own >= minutes)
        return [
          `the step "${label}" of the ${name} job in ${file} is bounded at ${own} minutes, not under its job's ${minutes}: lower it below the job's, or the job's bound fires first and names no step`,
        ];
      return [];
    });
  });
}
