/**
 * Where the repository's Actions workflow is, how it parses, and which of its steps is the gate's.
 *
 * Read by the guard that holds the file to the repository (`ci-workflow.test.ts`) and by the tests that run a step's own script
 * (`ci-gate.boundary.test.ts`, `ci-build.boundary.test.ts`, `ci-scan.boundary.test.ts`): one writer for the path and for what each of
 * those steps is, so the two cannot drift apart. What is about the repository and not about this workflow is not here: the owned paths
 * and the private packages are written where their one reader is (`repo-guards.test.ts`).
 */
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const ROOT = path.join(import.meta.dirname, '..', '..', '..');

/** The workflow, as every sentence that refuses it names it to the person who must fix it. */
export const FILE = '.github/workflows/ci.yml';

/** The job that reports the one context branch protection requires. */
export const GATE = 'ci';

/** The job whose matrix holds the legs: one workspace on one node version. */
export const LEGS = 'test';

/** The job whose matrix holds the e2e's shards: one shard of the pages each. */
export const E2E = 'e2e';

/** The job that sums every shard's page time against the bound a whole e2e run is held to. */
export const BOUND = 'e2e-bound';

/** The job that builds the board and refuses a generated file the build or the theme generator would rewrite. */
export const BUILD = 'build';

/**
 * The paths the build job's staleness step guards, each generated by a command and never edited: a stale one is a diff a person has not
 * committed, and the step names the command that writes it. A path here that the repository does not have is refused by the guard.
 */
export const GENERATED = ['apps/web/src/routeTree.gen.ts', 'apps/web/theme/'];

/** What the build job's staleness step is called, so the guard and the boundary test find the same step. */
export const STALE_STEP = 'Refuse a stale generated file';

/** The command the shards run, which the guard reads the shard's flags off. */
export const E2E_COMMAND = 'npm run e2e';

export type Step = { name?: string; uses?: string; with?: Record<string, unknown>; run?: string; env?: Record<string, string> };

export type Job = {
  if?: string;
  needs?: string[];
  strategy?: { 'fail-fast'?: boolean; matrix?: Record<string, unknown[]> };
  steps?: Step[];
};

export type Workflow = {
  name?: string;
  on?: Record<string, { branches?: string[] } | null>;
  permissions?: Record<string, string>;
  concurrency?: { group?: string; 'cancel-in-progress'?: unknown };
  jobs: Record<string, Job>;
};

/** The workflow's own text, which two clauses read rather than its parse: a word in a comment is in the file all the same. */
export const workflowText = (): string => fs.readFileSync(path.join(ROOT, FILE), 'utf8');

export const readWorkflow = (text = workflowText()): Workflow => yaml.load(text) as Workflow;

/** The steps of `job` that run a command. */
export const runSteps = (workflow: Workflow, job: string): Step[] =>
  (workflow.jobs[job]?.steps ?? []).filter((step) => step.run !== undefined);

/** The e2e job's step that runs the e2e itself, which must hand it the leg's shard and the matrix's count. */
export const shardRunStep = (workflow: Workflow): Step | undefined =>
  runSteps(workflow, E2E).find((step) => step.run?.includes(E2E_COMMAND) === true);

/**
 * The build job's staleness step, by its name: what it decides is run rather than matched (`ci-build.boundary.test.ts`), since a
 * `git diff --exit-code` and a `git diff --name-only` that forgets to fail read alike to a pattern.
 */
export const staleStep = (workflow: Workflow): Step | undefined => runSteps(workflow, BUILD).find((step) => step.name === STALE_STEP);

/** The gate's steps that run a command: the one that turns the needed jobs' results into the `ci` context. */
export const gateSteps = (workflow: Workflow): Step[] => runSteps(workflow, GATE);

/** The job that scans the push's or the pull request's new commits for a secret. */
export const SCAN = 'gitleaks';

/** What the scan is configured by, and the one file that says what it allows, as the sentences that refuse a wider scan name it. */
export const SCAN_CONFIG = '.gitleaks.toml';

/**
 * What the scan job's step that proves its own allowlist is called, so the guard and the boundary test find the same step. What it
 * decides is run rather than matched (`ci-scan.boundary.test.ts`): the config's meaning is not in its text, and neither is the step's.
 */
export const ALLOWLIST_STEP = 'Prove the allowlist allows the stubs and nothing wider';

/** The scan job's step that scans the push's own commits, by the flags it carries: the one step of the job that reads git. */
export const scanStep = (workflow: Workflow): Step | undefined =>
  runSteps(workflow, SCAN).find((step) => step.run?.includes('--log-opts') === true);

/** The scan job's step that proves its allowlist, by its name. */
export const allowlistStep = (workflow: Workflow): Step | undefined =>
  runSteps(workflow, SCAN).find((step) => step.name === ALLOWLIST_STEP);
